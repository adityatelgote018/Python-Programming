#Take two numbers as input and perform addition, subtraction, multiplication, division, modulus,
#and exponentiation using Python operators.
a = int(input("Enter first number : "))
b = int(input("Enter second number: "))
 
print("Addition :", a + b)
print("Subtraction :", a - b)
print("Multiplication :", a * b)
print("Division :", a / b)
print("Modulus :", a % b)
print("Exponent :", a ** b)